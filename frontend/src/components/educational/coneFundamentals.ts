export const CONE_NM_MIN = 390;
export const CONE_NM_MAX = 700;

/** Sensitivity of each cone at a wavelength (linear interpolation between 5 nm rows). */
export function coneResponse(nm: number): { L: number; M: number; S: number } {
  const clamped = Math.min(CONE_NM_MAX, Math.max(CONE_NM_MIN, nm));
  const i = Math.min(CONE_FUNDAMENTALS.length - 2, Math.floor((clamped - CONE_NM_MIN) / 5));
  const [n0, l0, m0, s0] = CONE_FUNDAMENTALS[i];
  const [, l1, m1, s1] = CONE_FUNDAMENTALS[i + 1];
  const t = (clamped - n0) / 5;
  return { L: l0 + (l1 - l0) * t, M: m0 + (m1 - m0) * t, S: s0 + (s1 - s0) * t };
}
